import { execFileSync } from 'node:child_process';
import { readFileSync, writeFileSync } from 'node:fs';
import { createHash } from 'node:crypto';
import path from 'node:path';

const root = path.resolve(import.meta.dirname, '..');
const command = process.env.npm_execpath;
const output = command
  ? execFileSync(process.execPath, [command, 'licenses', 'list', '--prod', '--json'], { cwd: root, encoding: 'utf8' })
  : process.platform === 'win32'
    ? execFileSync('cmd.exe', ['/d', '/s', '/c', 'pnpm licenses list --prod --json'], { cwd: root, encoding: 'utf8', windowsHide: true })
    : execFileSync('pnpm', ['licenses', 'list', '--prod', '--json'], { cwd: root, encoding: 'utf8' });
const groups = JSON.parse(output), allowed = new Set(['MIT', 'ISC', 'Apache-2.0', 'BSD-2-Clause', 'BSD-3-Clause', '0BSD', 'MIT AND ISC AND BSD-3-Clause']);
const rows = Object.entries(groups).flatMap(([license, packages]) => {
  if (!allowed.has(license)) throw new Error(`Review required for license: ${license}`);
  return packages.map(pkg => ({ name: pkg.name, version: [...pkg.versions].sort().join(', '), license }));
}).sort((a, b) => a.name.localeCompare(b.name, 'en'));
const hash = createHash('sha256').update(readFileSync(path.join(root, 'pnpm-lock.yaml'))).digest('hex');
const report = `# Third-party production licenses

Generated by \`pnpm licenses:report\` using \`pnpm licenses list --prod --json\` across both workspace packages.
Lockfile SHA-256: \`${hash}\`.
Includes direct and transitive production dependencies; development tools are excluded.

All ${rows.length} package records use Apache-2.0-compatible permissive licenses: MIT, ISC, Apache-2.0, BSD-3-Clause, 0BSD, or the combined MIT AND ISC AND BSD-3-Clause notice for victory-vendor.
The combination requires retaining each constituent notice. No unknown or copyleft license is present in this inventory.
Preserve upstream copyright, license and notice files when redistributing dependencies; Alba's license does not replace them.
The generator fails on an unreviewed license expression. Re-run after dependency or lockfile changes and review the diff.

| Package | Version(s) | SPDX license expression |
|---|---|---|
${rows.map(row => `| ${row.name} | ${row.version} | ${row.license} |`).join('\n')}
`;
writeFileSync(path.join(root, 'docs/third-party-licenses.md'), report);
console.log(`Recorded ${rows.length} production packages; all license expressions reviewed.`);
