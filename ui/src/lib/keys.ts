/** Query keys. A key is a prefix of the more specific ones, so `['orders', project]` covers every list of that project. */
export const keys = {
  session: ['session'] as const,
  projects: ['projects'] as const,
  overviewAll: ['overview-all'] as const,
  overview: (project: string) => ['overview', project] as const,
  projectOverview: (project: string) => ['project-overview', project] as const,
  producer: (project: string) => ['producer', project] as const,
  producerFacts: (project: string) => ['producer-facts', project] as const,
  producerInsights: (project: string) => ['producer-insights', project] as const,
  orders: (project: string, stage?: string) => (stage ? (['orders', project, stage] as const) : (['orders', project] as const)),
  order: (project: string, tag: string) => ['order', project, tag] as const,
  diff: (project: string, tag: string) => ['diff', project, tag] as const,
  readiness: (project: string, tag: string) => ['readiness', project, tag] as const,
  workers: (project: string) => ['workers', project] as const,
  resources: (project: string) => ['resources', project] as const,
  workerYaml: (project: string, id: string) => ['worker-yaml', project, id] as const,
  quota: (project: string, worker?: string) => (worker ? (['quota', project, worker] as const) : (['quota', project] as const)),
  runs: (project: string, filter = '') => ['runs', project, filter] as const,
  decisions: (project: string) => ['decisions', project] as const,
  evidence: (project: string, tag: string) => ['evidence', project, tag] as const,
  clean: (project: string) => ['clean', project] as const,
  cleanEvents: (project: string) => ['clean-events', project] as const,
  credits: (project: string) => ['credits', project] as const,
  lessons: (project: string, tag = '') => ['lessons', project, tag] as const,
  route: (project: string, tag: string) => ['route', project, tag] as const,
  skills: (project: string) => ['skills', project] as const,
  orderSkills: (project: string, tag: string) => ['order-skills', project, tag] as const,
  runLog: (project: string, key: string) => ['runlog', project, key] as const,
  runTranscript: (project: string, key: string) => ['runtranscript', project, key] as const,
  picks: (project: string) => ['picks', project] as const,
  art: (project: string) => ['art', project] as const,
  spend: (project: string) => ['spend', project] as const,
  usage: (project: string, days = 7) => ['usage', project, days] as const,
  docs: (project: string) => ['docs', project] as const,
  doc: (project: string, path: string) => ['doc', project, path] as const,
  docSearch: (project: string, q: string) => ['doc-search', project, q] as const,
};
export type QueryKey = readonly unknown[];
